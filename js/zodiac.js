// Sign `sign` (a ZODIAC entry) as an inline SVG string in currentColor,
// one rect per run of pixels, `px` CSS pixels a side (a whole multiple of
// 16 stays crisp).
export function zodiacSvg(sign, px = 32) {
  let rects = '';
  sign.rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      if (row[x] !== '#') continue;
      let end = x;
      while (row[end + 1] === '#') end++;
      rects += '<rect x="' + x + '" y="' + y + '" width="' + (end - x + 1) + '" height="1"/>';
      x = end;
    }
  });
  return '<svg class="zodiac" viewBox="0 0 16 16" width="' + px + '" height="' + px + '" fill="currentColor" shape-rendering="crispEdges" aria-hidden="true">' + rects + '</svg>';
}
